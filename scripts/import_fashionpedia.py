"""Import Fashionpedia's attribute names as proposed Fashion Dictionary terms.

    python scripts/import_fashionpedia.py [path/to/instances_attributes_val2020.json]

Without a path it downloads the file (about 15 MB) from Fashionpedia's public bucket. Writes
data/dictionary_proposed.json from scratch each time; terms already promoted into
data/dictionary.json are left out. Fashionpedia annotations are CC BY 4.0: keep the credit.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import requests

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from thread.dictionary import PROPOSED, load  # noqa: E402
from thread.fashionpedia import SOURCE, URL, build  # noqa: E402


def main() -> None:
    if len(sys.argv) > 1:
        raw = json.loads(Path(sys.argv[1]).read_text(encoding="utf-8"))
    else:
        resp = requests.get(URL, timeout=120)
        resp.raise_for_status()
        raw = resp.json()
    terms, matched, skipped = build(raw["attributes"], load())
    out = {"about": "Candidate terms awaiting review, generated by scripts/import_fashionpedia.py; do not edit "
                    "by hand. Names from the Fashionpedia ontology (Jia et al., 'Fashionpedia: Ontology, "
                    "Segmentation, and an Attribute Localization Dataset', ECCV 2020), used under CC BY 4.0. "
                    "Brackets removed, two spelling fixes, categories mapped to this dictionary.",
           "source": {**SOURCE, "file": URL, "version": raw.get("info", {}).get("version")},
           "terms": terms}
    PROPOSED.write_text(json.dumps(out, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    load()                                              # refuse to leave an invalid dictionary behind
    print(f"{len(terms)} proposed terms written to {PROPOSED.relative_to(ROOT)}")
    print(f"{len(matched)} already in the dictionary: " + ", ".join(f"{n} ({i})" for n, i in matched))
    print(f"{len(skipped)} skipped as placeholders or too generic: " + ", ".join(skipped))


if __name__ == "__main__":
    main()
